`timescale 1ns/1ps

module susskind_to_bin (input wire[3:0]A, output reg [3:0]Y);
	always @(*)
		begin
			case(A)
				{{1'b0 & 1'b0}, {1'b0 ^ 1'b0}, {1'b0 | 1'b0}, {1'b1 ~| 1'b0}}: Y = {A[3], A[2], A[1], A[2]};
				{{1'b0 ~^ 1'b1}, {1'b1 ~& 1'b1}, {1'b1, 1'b1}}: Y = {A[3], A[2], A[2], A[0]};
				{{&1'b0}, {|1'b1}, {^1'b1}, {~&1'b0}}: Y = {A[3], A[3], A[1], A[3]};
				{~|1'b1, ~^1'b0, 1'b1, 1'b0} : Y = {A[3], A[0], A[2], A[1]};
				{{1'b0 && 1'b1}, {1'b1 || 1'b1}, 1'b10, 1'b0} : Y = A;
				{1'b0, 1'b1, A[3], A[3]}: Y = {A[3], A[2], A[1], A[0]};
				{1'b1, A[3], 1'b0, A[1]}: Y = {A[1], A[2], A[1], A[2]};
				{1'b1, 1'b1, 1'b1, 1'b0}: Y = {A[0] & A[0], A[3] | A[3], A[2] ^ A[0], A[0] ~| A[1]};
				{1'b1, 1'b1, 1'b1, 1'b1}: Y = {~A[3], A[3] ~& ~A[3], A[2] ~^ A[2], |A[1]};
				{1'b1, 1'b0, 1'b1, 1'b1}: Y = {&A[3], ^A[2], ~&A[3], ~|A[1]}; //1000
				{1'b1, 1'b0, 1'b0, 1'b1}: Y = ~{A[2], A[3], A[0], A[1]};
				{1'b1, 1'b0, 1'b1, 1'b0}: Y = {A[4], Y & 4'b00x0, 4'bxxxx, ~^A[0]};
				default: Y=4'b0000;
			endcase
		end
endmodule